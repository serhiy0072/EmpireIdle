namespace EmpireIdle.Domain.Enums
{
    /// <summary>
    /// Права в клані. Прапорці, а не порядок ролей: набір зростатиме
    /// (війни, кланові будівлі, скарбниця), і виводити нове право
    /// з рангу означало б переписувати ієрархію на кожну механіку.
    ///
    /// Ранг ролі лишається окремо — він відповідає на «кого саме»,
    /// тоді як дозвіл на «що взагалі можна».
    /// </summary>
    [Flags]
    public enum ClanPermission
    {
        None = 0,

        /// <summary>Приймати заявки й запрошувати.</summary>
        Recruit = 1,

        /// <summary>Виключати учасників нижчого рангу.</summary>
        Kick = 2,

        /// <summary>Призначати ролі учасникам нижчого рангу.</summary>
        AssignRoles = 4,

        /// <summary>Створювати, змінювати й видаляти самі ролі.</summary>
        ManageRoles = 8,

        /// <summary>Редагувати опис і політику вступу.</summary>
        EditProfile = 16,

        /// <summary>Будувати кланові споруди на карті.</summary>
        BuildStructures = 32,

        /// <summary>Розпустити клан. Тільки лідер — і при передачі лідерства теж.</summary>
        Disband = 64
    }
}
