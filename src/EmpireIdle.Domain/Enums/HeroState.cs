namespace EmpireIdle.Domain.Enums
{
    /// <summary>
    /// Де зараз герой. Ортогонально до маршу: марш знає, який герой його веде,
    /// а стан героя каже, чи вільний він узагалі.
    ///
    /// Гарнізону окремого значення немає: вільний герой боронить рідне село
    /// за замовчуванням, тому Idle і є «стоїть у гарнізоні».
    /// </summary>
    public enum HeroState
    {
        /// <summary>Вдома й вільний. Боронить власний гарнізон, доступний для маршу.</summary>
        Idle = 1,

        /// <summary>Закріплений за маршем або підкріпленням. Недоступний.</summary>
        Deployed = 2,

        /// <summary>У госпіталі після поразки. Недоступний до кінця лікування.</summary>
        Wounded = 3
    }
}
