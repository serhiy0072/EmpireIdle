namespace EmpireIdle.Domain.Enums
{
    /// <summary>
    /// Вид вміння героя (GDD §6.1, рішення 08.10.2026): де й як воно діє.
    /// </summary>
    public enum SkillKind
    {
        /// <summary>
        /// Одне на героя. У данжі — удар чи підтримка з перезарядкою, гравець або автобій
        /// вирішує, коли бити; у марші — бонус війську.
        /// </summary>
        Active = 0,

        /// <summary>Бойова пасивка: постійний бонус війську в маршах і обороні.</summary>
        Passive = 1,

        /// <summary>
        /// Спрацьовує в данжі саме, раз на кілька ходів героя; у марші — бонус війську.
        /// </summary>
        Periodic = 2,

        /// <summary>Небойова: економіка й логістика (швидкість маршу). Лише у звичайних героїв.</summary>
        Utility = 3
    }
}
