namespace EmpireIdle.Domain.Enums
{
    /// <summary>
    /// Бойова властивість, яку дає лише унікальний артефакт і яка не росте
    /// від прокачки предмета. Діє тільки в покроковому бою данжів: армійський
    /// бій рахується іншою формулою й про ці механіки не знає.
    /// </summary>
    public enum DungeonStat
    {
        /// <summary>Додає до шансу критичного удару (частка: 0.1 = +10%).</summary>
        CritChance = 0,

        /// <summary>Повертає частку завданої шкоди здоров'ям виконавця.</summary>
        Lifesteal = 1,

        /// <summary>Зменшує отриману шкоду на частку.</summary>
        DamageReduction = 2,

        /// <summary>Додає енергію за кожен власний удар понад звичайний приріст.</summary>
        EnergyOnAttack = 3
    }
}
