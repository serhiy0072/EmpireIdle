namespace EmpireIdle.Domain.Enums
{
    /// <summary>
    /// Бойова властивість героя в данжі — з бонусів наборів і заточки (див. DungeonStats).
    /// Діє тільки в покроковому бою данжів: армійський бій рахується іншою формулою
    /// й про ці механіки не знає.
    /// </summary>
    public enum DungeonStat
    {
        /// <summary>Додає до шансу критичного удару (частка: 0.1 = +10%).</summary>
        CritChance = 0,

        /// <summary>Повертає частку завданої шкоди здоров'ям виконавця.</summary>
        Lifesteal = 1,

        /// <summary>Зменшує отриману шкоду на частку.</summary>
        DamageReduction = 2,

        /// <summary>
        /// Скорочує перезарядку активного вміння на стільки ходів (ціле), але між двома
        /// застосуваннями завжди лишається щонайменше один звичайний удар.
        /// </summary>
        CooldownReduction = 3,

        /// <summary>Додає до множника криту (частка: 0.2 = ×1.6 → ×1.8).</summary>
        CritPower = 4,

        /// <summary>Підсилює шкоду активного й періодичних вмінь; звичайний удар — ні.</summary>
        SkillDamage = 5,

        /// <summary>Шанс заблокувати удар по герою.</summary>
        BlockChance = 6,

        /// <summary>Додає до частки шкоди, яку гасить блок, понад базову.</summary>
        BlockPower = 7,

        /// <summary>Оберіг: щит на старті забігу часткою максимального здоров'я.</summary>
        Ward = 8
    }
}
