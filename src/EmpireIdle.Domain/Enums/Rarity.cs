namespace EmpireIdle.Domain.Enums
{
    /// <summary>
    /// Рідкість героя або предмета. Спільна шкала для обох: гача видає
    /// і те, і те з одного пулу, тож дві різні шкали означали б перетворення
    /// на кожному дропі.
    ///
    /// Enum, а не рядок: набір закритий і змінюється лише разом із кодом,
    /// а рядок дозволяв би конфігу привезти неіснуючу рідкість і впасти
    /// вже під час роздачі.
    /// </summary>
    public enum Rarity
    {
        /// <summary>Звичайний. Продається за золото в залі героїв, у банерах відсутній.</summary>
        Common = 1,

        /// <summary>Рідкісний. Банери й лутбокси, а також стартові нагороди за сюжет.</summary>
        Rare = 2,

        /// <summary>Унікальний. Лише банери й лутбокси.</summary>
        Unique = 3
    }
}
