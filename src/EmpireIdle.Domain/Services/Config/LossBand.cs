namespace EmpireIdle.Domain.Services.Config
{
    /// <summary>
    /// Смуга втрат для однієї комбінації «сторона × результат».
    ///
    /// Втрати ростуть від Min до Max разом із силою супротивника, тож
    /// нижня межа програшу дорівнює верхній межі перемоги тієї ж сторони,
    /// і крива ніде не перетинається: за того самого співвідношення сил
    /// програти завжди дорожче, ніж перемогти.
    /// </summary>
    public class LossBand
    {
        /// <summary>Частка втрат проти рівного супротивника.</summary>
        public double Min { get; set; }

        /// <summary>Частка втрат проти незрівнянно сильнішого.</summary>
        public double Max { get; set; }
    }
}
