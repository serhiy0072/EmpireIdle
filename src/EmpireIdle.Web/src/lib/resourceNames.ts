/**
 * Назви ресурсів і валют у родовому відмінку — для відмов на кшталт
 * «Не вистачає золота» чи «Склад деревини заповнений». Каталог дає лише
 * називний відмінок, тому тут власна мапа.
 */
const GENITIVE: Record<string, string> = {
  gold: "золота",
  wood: "деревини",
  stone: "каменю",
  iron: "заліза",
  food: "їжі",
  gems: "самоцвітів",
  seals: "печаток призову",
  "dungeon-energy": "енергії данжів",
};

/** Невідомий ключ повертається як є: краще сирий ключ, ніж порожнє місце в тексті. */
export function resourceGenitive(key: string): string {
  return GENITIVE[key] ?? key;
}
